        <h2>Important points to consider when making your will using <?php echo $_SESSION['sitename'];?>'s Will Kit.</h2>
        <ol>
          <li>
            <strong>Make sure you choose an Executor who you trust to manage your estate after you have passed.</strong>
          </li>
          <p>
          	The executor you choose should have enough competence to manage the financial matters of your estate, such as clearing any taxation and other liabilities, and correctly apportioning 
          	the remaining estate to your beneficiaries to suit your wishes. Your chosen executor should be expected to outlive you. If they die before you, then you should change, re-download and re-sign your will to nominate another executor.
          	It is a wise move to appoint more than one executor. <?php echo $_SESSION['sitename'];?> allows you to appoint more than one executor and to determine how they should act - jointly, or alone
          	(the first surviving executor in your list).
          </p>
          <li>
            <strong>Blended families (that is, children from several relationships, possibly including step children) need to be considered carefully.</strong>
          </li>
          <p>
          	If you do not adequately provide for your spouse (including de-facto spouse) and all your children (including step children), they may be able to legally contest your will.
          	So, it is important to be clear about what you wish to leave to whom. The <?php echo $_SESSION['sitename'];?> process requires that you define all your beneficiaries by name (and relationship), so
          	that, when you leave a gift or share of your estate to them, they are explicitly named.
          </p>
          <p>	
          	Removing any ambiguity from your will makes it less likely to be successfully contested.
          </p>
          <li>
            <strong>If you have assets owned by trusts (such as family trusts) and companies, you need to know that these assets may not be included in your estate.</strong>
          </li>
          <p>
          	If you have a trust or company that owns assets that you would like to distribute to your beneficiaries, then we strongly recommend that you do use a solicitor who
          	is knowledgeable about complex estate planning. You will pay significantly more to have your estate planning documents setup, but it will save problems after you
          	have passed.
          </p>
          <li>
            <strong>Your superannuation may not be automatically included in your estate, and therefore is not governed by the wishes in your Will.</strong>
          </li>
          <p>
          	Under current superannuation law in Australia, the trustee of your superannuation fund has the discretion and obligation to decide who will receive your super and your insurance benefits.
          	You may have made beneficiary nominations when you setup your fund contributions, however, these nominations are not binding on the trustee.
          </p>	
          <p>          	
          	The trustee of the super fund will distribute your benefits amongst your dependants and your estate in whatever way it believes is fair and reasonable.
          	They will take into account the nomination you completed on your application form (these nominations are not binding unless you make what is called a <em>Binding Nomination</em>).
          </p>
          <p>
            To make sure that your superannuation and associated insurance benefits are included in your estate (and therefore subject to the wishes in your will) you need to make 
            a <em>Binding Nomination</em>. You will need to contact your super fund to make a <em>Binding Nomination</em>.
          </p>
          <li>
            <strong>Be aware that no Last Will and Testament is immune from being challenged, no matter how well written.</strong>
          </li>
          <p>
          	To minimise the success of any legal challenges to your will, make sure that you adequately cater for all your dependents in your will, and if you wish to leave gifts or
          	a share of your estate to a non-dependent (a friend, a carer, a charity), then include your reasons for leaving the gift or share. It is often family members that contest 
          	wills, so be clear about who gets what and why.
          </p>
                    
        </ol>
